import Fastify from 'fastify';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { randomUUID } from 'node:crypto';
import { openDb } from '../src/db/schema.js';
import { registerCommandPadRoutes, PadRequest } from '../src/routes/commandPad.js';
import { ClefPad, needsPadClarification } from '../src/computer/clefPad.js';
import { registerAuth, GATEWAY_TOKEN_ENV } from '../src/auth/index.js';

const cleanups: Array<() => Promise<void>> = [];
afterEach(async () => { for (const close of cleanups.splice(0)) await close(); });
function fixture(busy = () => false) {
  const server = Fastify(), db = openDb(':memory:');
  const execute = vi.fn(async () => 'Verified test action.');
  const clef = new ClefPad();
  const classify = vi.spyOn(clef, 'classify').mockResolvedValue('open');
  const running = registerCommandPadRoutes(server, db, busy, execute, clef);
  cleanups.push(async () => { await server.close(); db.close(); });
  return { server, db, execute, classify, running };
}
const body = () => ({ requestId: randomUUID(), action: 'open', value: 'Calculator' });
describe('bounded local command pad', () => {
  it('requires gateway authentication before classification or execution', async () => {
    vi.stubEnv(GATEWAY_TOKEN_ENV, 'command-pad-test-token');
    const server = Fastify(), db = openDb(':memory:');
    registerAuth(server);
    const execute = vi.fn(async () => 'done'), clef = new ClefPad();
    const classify = vi.spyOn(clef, 'classify').mockResolvedValue('open');
    registerCommandPadRoutes(server, db, () => false, execute, clef);
    try {
      for (const path of ['classify', 'execute']) {
        expect((await server.inject({ method: 'POST', url: '/v1/command-pad/' + path, payload: path === 'classify' ? { text: 'open' } : body() })).statusCode).toBe(401);
      }
      expect((await server.inject({ method: 'GET', url: '/v1/command-pad/receipts/' + randomUUID() })).statusCode).toBe(401);
      expect(execute).not.toHaveBeenCalled(); expect(classify).not.toHaveBeenCalled();
    } finally { await server.close(); db.close(); vi.unstubAllEnvs(); }
  });
  it.each(['Do not close the window', 'Don’t open Notes', 'If I said close', 'send hello', '"open Calculator"'])(
    'requires clarification for %s', text => expect(needsPadClarification(text)).toBe(true));
  it('classification cannot execute and contains no target generated by the model', async () => {
    const f = fixture();
    const r = await f.server.inject({ method: 'POST', url: '/v1/command-pad/classify', payload: { text: 'Open Calculator' } });
    expect(r.json()).toEqual({ action: 'open', executed: false }); expect(f.execute).not.toHaveBeenCalled();
  });
  it('runs buttons without calling Clef; repeated IDs cannot execute twice', async () => {
    const f = fixture(), payload = body();
    for (let i = 0; i < 2; i++) expect((await f.server.inject({ method: 'POST', url: '/v1/command-pad/execute', payload })).statusCode).toBe(200);
    expect(f.execute).toHaveBeenCalledOnce(); expect(f.classify).not.toHaveBeenCalled();
    expect((await f.server.inject({ method: 'POST', url: '/v1/command-pad/execute', payload: { ...payload, value: 'Notes' } })).statusCode).toBe(409);
  });
  it('unknown outcomes are never replayed', async () => {
    const f = fixture(), payload = body();
    await f.server.inject({ method: 'POST', url: '/v1/command-pad/execute', payload });
    f.db.prepare('UPDATE command_pad_receipts SET summary = NULL').run();
    expect((await f.server.inject({ method: 'POST', url: '/v1/command-pad/execute', payload })).json().summary).toContain('not repeated');
    expect(f.execute).toHaveBeenCalledOnce();
  });
  it('refuses concurrent terminal work', async () => {
    const f = fixture(() => true);
    expect((await f.server.inject({ method: 'POST', url: '/v1/command-pad/execute', payload: body() })).statusCode).toBe(409);
    expect(f.execute).not.toHaveBeenCalled();
  });
  it.each([
    { action: 'open', value: '/bin/sh' }, { action: 'send', value: 'hi' },
    { action: 'close', value: 'Notes' }, { action: 'type', value: '' },
    { action: 'search', value: 'x'.repeat(1001) }, { action: 'type', value: '\0' },
    { action: 'typeFocused', value: 'hello\n' }, { action: 'typeFocused', value: 'hello\r' },
    { action: 'window', value: 'quit' }, { action: 'window', value: 'restore' }, { action: 'browser', value: 'send' },
    { action: 'navigate', value: 'javascript:alert(1)' }, { action: 'navigate', value: 'https://user:secret@example.com/' },
  ])('rejects unsafe/unsupported payload %j', input => {
    expect(PadRequest.safeParse({ requestId: randomUUID(), ...input }).success).toBe(false);
  });
  it.each([
    { action: 'window', value: 'left' }, { action: 'window', value: 'maximize' },
    { action: 'browser', value: 'nextTab' }, { action: 'browser', value: 'focusAddress' },
    { action: 'navigate', value: 'http://localhost:8787/CaseSensitive' }, { action: 'open', value: 'Safari' },
  ])('validates and deduplicates new bounded action %j', async input => {
    const f = fixture(), payload = { requestId: randomUUID(), ...input };
    expect(PadRequest.safeParse(payload).success).toBe(true);
    for (let i=0; i<2; i++) expect((await f.server.inject({method:'POST',url:'/v1/command-pad/execute',payload})).statusCode).toBe(200);
    expect(f.execute).toHaveBeenCalledOnce(); expect(f.classify).not.toHaveBeenCalled();
  });
  it('advertises only the fixed actions without arbitrary key/macro controls', async () => {
    const f=fixture();
    const catalog=(await f.server.inject({method:'GET',url:'/v1/command-pad'})).json();
    expect(catalog.apps).toContain('Safari');
    expect(catalog.windowActions).toEqual(['minimize','maximize','left','right']);
    expect(catalog.browserActions).toContain('nextTab');
    expect(catalog.actions).not.toContain('send');
  });
  it('rejects invalid receipt IDs and reports absent receipts without executing', async () => {
    const f=fixture();
    expect((await f.server.inject({method:'GET',url:'/v1/command-pad/receipts/not-a-uuid'})).statusCode).toBe(400);
    const missing=await f.server.inject({method:'GET',url:'/v1/command-pad/receipts/'+randomUUID()});
    expect(missing.statusCode).toBe(404); expect(missing.json().message).toContain('not automatically retry');
    expect(f.execute).not.toHaveBeenCalled(); expect(f.classify).not.toHaveBeenCalled();
  });
  it('reports a live request as running, then reads back its completed summary without replay', async () => {
    const f=fixture(), payload=body();
    let complete: ((value: string) => void) | undefined;
    f.execute.mockImplementationOnce(() => new Promise<string>(resolve => { complete=resolve; }));
    const pending=f.server.inject({method:'POST',url:'/v1/command-pad/execute',payload});
    await vi.waitFor(() => expect(f.execute).toHaveBeenCalledOnce());
    const read=() => f.server.inject({method:'GET',url:'/v1/command-pad/receipts/'+payload.requestId});
    expect((await read()).json()).toEqual({summary:null,state:'running'});
    complete!('Nothing changed. Blocked by a dialog.'); await pending;
    // completed is receipt availability, not a successful mutation assertion.
    expect((await read()).json()).toEqual({summary:'Nothing changed. Blocked by a dialog.',state:'completed'});
    expect(f.execute).toHaveBeenCalledOnce();
  });
  it('treats a persisted unfinished receipt from a prior runtime as unknown', async () => {
    const f=fixture(), id=randomUUID();
    f.db.prepare('INSERT INTO command_pad_receipts (id,digest) VALUES (?,?)').run(id,'old-runtime-digest');
    const response=await f.server.inject({method:'GET',url:'/v1/command-pad/receipts/'+id});
    expect(response.json()).toEqual({summary:null,state:'unknown'});
    expect(f.execute).not.toHaveBeenCalled();
  });
});
